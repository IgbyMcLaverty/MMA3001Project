def eval_svr(inputFileLoc,modelFileLoc):
    """
    Evaluates a model saved by train_svr on a dataset (e.g. a validation set) by running svr_controller
    on every row. Prints and returns the RMSE and shows a figure of the residuals
    (actual - predicted extension) against each input and against the predicted extension.
    Rows where undershot or overshot equal 1 are excluded.
    
    Args:
        inputFileLoc (string): The location of the evaluation data csv file. Include directory and .csv in string
            Columns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate","extension","undershot","overshot"]
        modelFileLoc (string): The location of the model saved by train_svr. Include directory and .npz in string
    
    Returns:
        rmse (float): The root mean squared error between the predicted and actual extension
    """
    global SVR_MODEL_FILE, _svrModel

    data = pd.read_csv(inputFileLoc)
    totalRows = len(data)

    # only keep runs that neither undershot nor overshot the target apogee
    data = data[(data["undershot"] == 0) & (data["overshot"] == 0)]
    print(f"Evaluating on {len(data)} of {totalRows} rows")

    featureColumns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate"]
    features = data[featureColumns].to_numpy(dtype=float)
    labels = data["extension"].to_numpy(dtype=float)

    # svr_controller loads from SVR_MODEL_FILE, so point it at the requested model for this evaluation
    # and put everything back afterwards
    originalModelFile = SVR_MODEL_FILE
    SVR_MODEL_FILE = modelFileLoc
    _svrModel = None
    try:
        predictions = np.array([
            svr_controller(row[0],row[1],row[2],0.0,row[3],row[4],row[5])
            for row in features
        ])

        # hyperparameters saved with the model, used for the figure title
        C = float(_svrModel["C"])
        epsilon = float(_svrModel["epsilon"])
        gammaValue = float(_svrModel["gamma"])
    finally:
        SVR_MODEL_FILE = originalModelFile
        _svrModel = None

    rmse = np.sqrt(np.mean((predictions - labels)**2))
    print(f"RMSE on evaluation data: {rmse}")

    # residuals (actual - predicted) against each input and against the predicted extension
    residuals = labels - predictions
    plotX = [features[:,i] for i in range(len(featureColumns))] + [predictions]
    plotLabels = featureColumns + ["predicted extension"]

    fig, axes = plt.subplots(2, 4, figsize=(16, 8))
    axes = axes.flatten()
    for ax, x, label in zip(axes, plotX, plotLabels):
        ax.scatter(x, residuals, s=4, alpha=0.3)
        ax.axhline(0, color="red", linewidth=1)
        ax.set_xlabel(label)
        ax.set_ylabel("residual")
        ax.set_title(f"Residuals vs {label}")
    axes[-1].axis("off") # 7 plots on a 2x4 grid, so hide the unused panel

    fig.suptitle(f"SVR evaluation residuals: C={C:.4g}, epsilon={epsilon:.4g}, gamma={gammaValue:.4g}, RMSE={rmse:.4g}")
    fig.tight_layout(rect=[0, 0, 1, 0.96]) # leave room at the top for the figure title
    plt.show()

    return rmse

