        loaded = np.load(LINEAR_REGRESSION_MODEL_FILE)
        lrIntercept = float(loaded["lrIntercept"])
        lrAltCoef = float(loaded["lrAltCoef"])
        lrVelCoef = float(loaded["lrVelCoef"])
        lrSeaTempCoef = float(loaded["lrSeaTempCoef"])
        lrSeaPressureCoef = float(loaded["lrSeaPressureCoef"])
