def train_svr(inputFileLoc,modelFileLoc,C,epsilon,gamma):
    """
    Loads training data, fits a support vector regression (RBF kernel) for extension and saves the
    model to a .npz file so svr_controller can run without retraining.
    Rows where undershot or overshot equal 1 are excluded from training.
    Also shows a figure of the residuals (actual - predicted extension) against each input
    and against the predicted extension, using the training rows. The figure title shows the
    C, epsilon and gamma values used (gamma as the number it resolves to).
    
    Args:
        inputFileLoc (string): The location of the training data csv file. Include directory and .csv in string
            Columns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate","extension","undershot","overshot"]
        modelFileLoc (string): The location to save the trained model to. Include directory and .npz in string
            (this should match SVR_MODEL_FILE so the controller finds it)
        C (float): The regularization parameter of the SVR
        epsilon (float): The width of the epsilon tube of the SVR, in units of extension
        gamma (float or string): The RBF kernel coefficient. A number, or "scale" or "auto" as in scikit-learn
    
    Returns:
        None
    """
    global _svrModel

    data = pd.read_csv(inputFileLoc)
    totalRows = len(data)

    # only keep runs that neither undershot nor overshot the target apogee
    data = data[(data["undershot"] == 0) & (data["overshot"] == 0)]
    print(f"Training on {len(data)} of {totalRows} rows")

    featureColumns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate"]
    features = data[featureColumns].to_numpy(dtype=float)
    labels = data["extension"].to_numpy(dtype=float)

    # standardize the features, the controller applies the same means and stds
    means = features.mean(axis=0)
    stds = features.std(axis=0)
    stds[stds == 0] = 1.0
    scaledFeatures = (features - means)/stds

    # resolve gamma to a number so it can be saved and used by the controller
    if gamma == "scale":
        gammaValue = 1.0/(scaledFeatures.shape[1]*scaledFeatures.var())
    elif gamma == "auto":
        gammaValue = 1.0/scaledFeatures.shape[1]
    else:
        gammaValue = float(gamma)

    model = SVR(kernel="rbf", C=C, epsilon=epsilon, gamma=gammaValue)
    model.fit(scaledFeatures, labels)

    np.savez(modelFileLoc,
             supportVectors=model.support_vectors_,
             dualCoef=model.dual_coef_[0],
             intercept=model.intercept_[0],
             gamma=gammaValue,
             means=means,
             stds=stds)

    # make sure the controller reloads the newly saved model on its next call
    _svrModel = None

    predictions = model.predict(scaledFeatures)
    rmse = np.sqrt(np.mean((predictions - labels)**2))

    print(f"Number of support vectors: {len(model.support_)}")
    print(f"RMSE on training data: {rmse}")
    print(f"Model saved to {modelFileLoc}")

    # residuals (actual - predicted) against each input and against the predicted extension
    residuals = labels - predictions
    plotX = [features[:,i] for i in range(len(featureColumns))] + [predictions]
    plotLabels = featureColumns + ["predicted extension"]

    fig, axes = plt.subplots(2, 4, figsize=(16, 8))
    axes = axes.flatten()
    for ax, x, label in zip(axes, plotX, plotLabels):
        ax.scatter(x, residuals, s=4, alpha=0.3)
        ax.axhline(0, color="red", linewidth=1)
        ax.set_xlabel(label)
        ax.set_ylabel("residual")
        ax.set_title(f"Residuals vs {label}")
    axes[-1].axis("off") # 7 plots on a 2x4 grid, so hide the unused panel

    # title for the whole figure showing the hyperparameters used (gamma as the resolved number)
    fig.suptitle(f"SVR residuals: C={C:.4g}, epsilon={epsilon:.4g}, gamma={gammaValue:.4g}")
    fig.tight_layout(rect=[0, 0, 1, 0.96]) # leave room at the top for the figure title
    plt.show()

