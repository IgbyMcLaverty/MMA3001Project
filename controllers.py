def train_nn_2(initialConditionsFileLoc,startModelFileLoc,modelFileLoc,populationSize=10,sigma=0.02,
               learningRate=0.1,maxGenerations=50,patience=10,seed=0):
    """
    Trains the neural network directly against the simulation using evolution strategies, starting
    from a model saved by train_nn (or train_nn_2). Each generation, mirrored random perturbations of
    the weights are run through the simulation on every initial condition, the perturbations are
    ranked by how close the achieved apogees are to TARGET_APOGEE (mean squared error) and the weights
    are moved towards the better ones. A step is only kept if it improves the loss.
    Training stops after maxGenerations, or when the loss has not improved for 'patience' generations,
    and the best weights found are saved to a .npz file in the same format as train_nn so nn_controller
    and eval_nn can use it. The network structure (layer sizes, activation) and input scaling are taken
    from the starting model.
    Each generation costs (populationSize + 1) simulation runs for every initial condition.
    
    Args:
        initialConditionsFileLoc (string): The location of the initial condition data csv file. Include directory and .csv in string
            Columns = ["initialAltitude","initialVelocity","seaTemp","groundPressure","lapserate"]
        startModelFileLoc (string): The location of the model to start from. Include directory and .npz in string
        modelFileLoc (string): The location to save the trained model to. Include directory and .npz in string
            (this should match NN_MODEL_FILE so the controller finds it)
        populationSize (int): The number of perturbed candidates per generation. Must be even (they are mirrored pairs)
        sigma (float): The standard deviation of the weight perturbations
        learningRate (float): The size of the step taken towards the better candidates, in weight units
        maxGenerations (int): The maximum number of generations to train for
        patience (int): Stop after this many generations without an improvement in the loss
        seed (int): The random seed used for the perturbations
    
    Returns:
        None
    """
    global _nnModel

    if populationSize < 2 or populationSize % 2 != 0:
        raise ValueError("populationSize must be an even number of at least 2")

    initialConditions = pd.read_csv(initialConditionsFileLoc)
    print(f"Loaded {len(initialConditions)} initial conditions")

    # load the starting model and flatten all of the weights and biases into a single parameter vector
    loaded = np.load(startModelFileLoc)
    numLayers = int(loaded["numLayers"])
    startWeights = [loaded[f"W{i}"] for i in range(numLayers)]
    startBiases = [loaded[f"b{i}"] for i in range(numLayers)]
    means = loaded["means"]
    stds = loaded["stds"]
    activationName = str(loaded["activation"])
    hiddenSizes = loaded["hiddenSizes"]
    savedLearningRate = float(loaded["learningRate"])
    activation = _NN_ACTIVATIONS_NUMPY[activationName]

    shapes = []
    pieces = []
    for weight, bias in zip(startWeights, startBiases):
        shapes.append((weight.shape, bias.shape))
        pieces.append(weight.ravel())
        pieces.append(bias.ravel())
    theta = np.concatenate(pieces).astype(float)

    def unpack(parameters):
        # split a flat parameter vector back into the weight and bias arrays of each layer
        weights = []
        biases = []
        position = 0
        for weightShape, biasShape in shapes:
            size = weightShape[0]*weightShape[1]
            weights.append(parameters[position:position+size].reshape(weightShape))
            position += size
            size = biasShape[0]
            biases.append(parameters[position:position+size])
            position += size
        return weights, biases

    def make_controller(parameters):
        # builds a controller with the given parameters, same forward pass as nn_controller
        weights, biases = unpack(parameters)
        lastLayer = len(weights) - 1

        def controller(alt,vel,acc,extension,seaTemp,seaPressure,lapseRate):
            x = (np.array([alt,vel,acc,seaTemp,seaPressure,lapseRate]) - means)/stds
            for i in range(lastLayer):
                x = activation(x @ weights[i] + biases[i])
            return float((x @ weights[lastLayer] + biases[lastLayer])[0])

        return controller

    def loss_of(parameters):
        # mean squared error between the achieved apogee and TARGET_APOGEE across all initial conditions
        # (mean of (apogee - target)^2 = (mean - target)^2 + variance)
        meanApogee, standardDeviation = eval_controller_mean(initialConditions, make_controller(parameters))
        return (meanApogee - TARGET_APOGEE)**2 + standardDeviation**2

    rng = np.random.default_rng(seed)
    numParameters = len(theta)
    half = populationSize//2

    bestLoss = loss_of(theta)
    initialLoss = bestLoss
    print(f"Starting RMSE from target apogee: {np.sqrt(bestLoss):.3f} m ({numParameters} parameters)")

    generationsSinceBest = 0
    lastGeneration = 0

    for generation in range(1, maxGenerations + 1):
        lastGeneration = generation

        # mirrored random perturbations of the current best weights
        noise = rng.standard_normal((half, numParameters))
        noise = np.vstack([noise, -noise])

        losses = np.array([loss_of(theta + sigma*noise[i]) for i in range(populationSize)])

        # rank the candidates (best loss -> +1, worst loss -> -1) and step towards the better ones
        ranks = np.argsort(np.argsort(-losses))
        scores = 2.0*ranks/(populationSize - 1) - 1.0
        candidate = theta + learningRate*np.mean(scores[:,None]*noise, axis=0)

        candidateLoss = loss_of(candidate)

        # only keep the step if it improved the loss
        if candidateLoss < bestLoss:
            theta = candidate
            bestLoss = candidateLoss
            generationsSinceBest = 0
        else:
            generationsSinceBest += 1

        print(f"{100*generation/maxGenerations:.0f}% (generation {generation}/{maxGenerations}) "
              f"best RMSE {np.sqrt(bestLoss):.3f} m, this generation's step {np.sqrt(candidateLoss):.3f} m, "
              f"generations since improved {generationsSinceBest}/{patience}")

        if generationsSinceBest >= patience:
            print(f"Early stopping at generation {generation}: loss has not improved for {patience} generations")
            break

    print(f"Stopped after {lastGeneration} generations")
    print(f"RMSE from target apogee improved from {np.sqrt(initialLoss):.3f} m to {np.sqrt(bestLoss):.3f} m")

    # save in the same format as train_nn
    weights, biases = unpack(theta)
    saved = {}
    for i in range(len(weights)):
        saved[f"W{i}"] = weights[i]
        saved[f"b{i}"] = biases[i]
    np.savez(modelFileLoc,
             numLayers=numLayers,
             means=means,
             stds=stds,
             activation=activationName,
             hiddenSizes=hiddenSizes,
             learningRate=savedLearningRate,
             **saved)

    # make sure the controller reloads the newly saved model on its next call
    _nnModel = None

    print(f"Model saved to {modelFileLoc}")

