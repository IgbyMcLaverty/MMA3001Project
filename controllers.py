# Linear regression coefficients for linear_regression_controller.
# Run train_linear_regression() and paste the printed values here.
lrIntercept = -9.796413955554184
lrAltCoef = 0.0012939384345603084
lrVelCoef = 0.004093336774252004
lrAccCoef = -0.1178210318044365
lrSeaTempCoef = 0.002307614046847522
lrSeaPressureCoef = 4.560181055376712e-05
lrLapseRateCoef = 4.579864426857139
 
def linear_regression_controller(alt,vel,acc,extension,seaTemp,seaPressure,lapseRate):
    """
    Evaluates a linear regression model to determine the extension value.
    Uses the module-level coefficients (lrIntercept, lrAltCoef, ...) defined in this file.
    The output is NOT clipped to [0,1], so the raw requested extension can be inspected.
    
    Args:
        alt (float): The current altitude of the rocket in meters
        vel (float): The current vertical velocity of the rocket in m/s
        acc (float): The current acceleration of the rocket in m/s^2
        extension (float): The current extension of the Air Brakes between 0 and 1 (unused by this controller)
        seaTemp (float): The temperature at sea level in kelvin
        seaPressure (float): The pressure at sea level in pascal
        lapseRate (float): The temperature lapse rate in K/m
    
    Returns:
        targetExtension (float): The new requested target extension based on the current conditions
    """
    return (lrIntercept
            + lrAltCoef*alt
            + lrVelCoef*vel
            + lrAccCoef*acc
            + lrSeaTempCoef*seaTemp
            + lrSeaPressureCoef*seaPressure
            + lrLapseRateCoef*lapseRate)

