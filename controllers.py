def train_linear_regression(inputFileLoc,modelFileLoc=LINEAR_REGRESSION_MODEL_FILE):
    """
    Loads training data, fits a linear regression for extension and saves the coefficients to a .npz file
    so linear_regression_controller can use them without having to rerun the training.
    Rows where undershot or overshot equal 1 are excluded from training.
    
    Args:
        inputFileLoc (string): The location of the training data csv file. Include directory and .csv in string
            Columns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate","extension","undershot","overshot"]
        modelFileLoc (string): The location to save the trained coefficients to. Include directory and .npz in string
            (this should match LINEAR_REGRESSION_MODEL_FILE so the controller finds it)
    
    Returns:
        None
    """
    global lrIntercept, lrAltCoef, lrVelCoef, lrSeaTempCoef, lrSeaPressureCoef, lrLapseRateCoef
 
    data = pd.read_csv(inputFileLoc)
    totalRows = len(data)
 
    # only keep runs that neither undershot nor overshot the target apogee
    data = data[(data["undershot"] == 0) & (data["overshot"] == 0)]
    print(f"Training on {len(data)} of {totalRows} rows")
 
    featureColumns = ["altitude","velocity","seaTemp","groundPressure","lapserate"]
    features = data[featureColumns].to_numpy(dtype=float)
    labels = data["extension"].to_numpy(dtype=float)
 
    # center and scale the features so the least squares solve is well conditioned
    # (groundPressure is ~1e5 while lapserate is ~1e-2), then convert back to raw units
    means = features.mean(axis=0)
    stds = features.std(axis=0)
    stds[stds == 0] = 1.0
    scaledFeatures = (features - means)/stds
 
    design = np.column_stack([np.ones(len(scaledFeatures)), scaledFeatures])
    solution, _, _, _ = np.linalg.lstsq(design, labels, rcond=None)
 
    coefs = solution[1:]/stds
    intercept = solution[0] - np.sum(coefs*means)
 
    predictions = features @ coefs + intercept
    rmse = np.sqrt(np.mean((predictions - labels)**2))
 
    print(f"RMSE on training data: {rmse}")

    # leave the controller using the new coefficients and save them so they can be loaded without retraining
    lrIntercept = float(intercept)
    lrAltCoef = float(coefs[0])
    lrVelCoef = float(coefs[1])
    lrSeaTempCoef = float(coefs[2])
    lrSeaPressureCoef = float(coefs[3])
    lrLapseRateCoef = float(coefs[4])
    np.savez(modelFileLoc,
             lrIntercept=lrIntercept,
             lrAltCoef=lrAltCoef,
             lrVelCoef=lrVelCoef,
             lrSeaTempCoef=lrSeaTempCoef,
             lrSeaPressureCoef=lrSeaPressureCoef,
             lrLapseRateCoef=lrLapseRateCoef)
    print(f"Coefficients saved to {modelFileLoc}")

    # residuals (actual - predicted) against each input and against the predicted extension
    residuals = labels - predictions
    plotX = [features[:,i] for i in range(len(featureColumns))] + [predictions, data["acceleration"]]
    plotLabels = featureColumns + ["predicted extension","acceleration"]
 
    fig, axes = plt.subplots(2, 4, figsize=(16, 8))
    axes = axes.flatten()
    for ax, x, label in zip(axes, plotX, plotLabels):
        ax.scatter(x, residuals, s=4, alpha=0.3)
        ax.axhline(0, color="red", linewidth=1)
        ax.set_xlabel(label)
        ax.set_ylabel("residual")
        ax.set_title(f"Residuals vs {label}")
    axes[-1].axis("off") # 7 plots on a 2x4 grid, so hide the unused panel
    fig.tight_layout()
    plt.show()

