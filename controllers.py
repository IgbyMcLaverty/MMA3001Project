def train_nn(inputFileLoc,modelFileLoc,hiddenSizes=(64,64),activation="relu",learningRate=1e-3,
             batchSize=128,maxEpochs=500,patience=30,valFraction=0.15,seed=0):
    """
    Loads training data, trains a neural network (PyTorch, CPU) for extension and saves the model
    to a .npz file so nn_controller can run without retraining.
    Rows where undershot or overshot equal 1 are excluded from training.
    A random portion of the remaining rows is held out as a validation set. Training stops when the
    validation loss has not improved for 'patience' epochs (or at maxEpochs) and the weights from the
    best validation epoch are kept.
    Also shows a figure of the residuals (actual - predicted extension) against each input
    and against the predicted extension, with the training and held-out rows in different colours.
    
    Args:
        inputFileLoc (string): The location of the training data csv file. Include directory and .csv in string
            Columns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate","extension","undershot","overshot"]
        modelFileLoc (string): The location to save the trained model to. Include directory and .npz in string
            (this should match NN_MODEL_FILE so the controller finds it)
        hiddenSizes (sequence of int): The number of neurons in each hidden layer, e.g. (64,64) or [32,32,16]
        activation (string): The hidden layer activation: "relu", "tanh", "sigmoid", "silu" or "leaky_relu"
        learningRate (float): The learning rate of the Adam optimizer
        batchSize (int): The mini-batch size
        maxEpochs (int): The maximum number of epochs to train for
        patience (int): Stop after this many epochs without an improvement in validation loss
        valFraction (float): The fraction of the rows held out for validation
        seed (int): The random seed used for the validation split and the network initialisation
    
    Returns:
        None
    """
    global _nnModel

    if activation not in _NN_ACTIVATIONS_TORCH:
        raise ValueError(f"activation must be one of {list(_NN_ACTIVATIONS_TORCH)}")

    data = pd.read_csv(inputFileLoc)
    totalRows = len(data)

    # only keep runs that neither undershot nor overshot the target apogee
    data = data[(data["undershot"] == 0) & (data["overshot"] == 0)]
    print(f"Training on {len(data)} of {totalRows} rows")

    featureColumns = ["altitude","velocity","seaTemp","groundPressure","lapserate"]
    features = data[featureColumns].to_numpy(dtype=float)
    labels = data["extension"].to_numpy(dtype=float)

    # random split into training and validation rows
    rng = np.random.default_rng(seed)
    order = rng.permutation(len(features))
    numVal = int(round(valFraction*len(features)))
    valIdx = order[:numVal]
    trainIdx = order[numVal:]

    # standardize using the training rows only, the controller applies the same means and stds
    means = features[trainIdx].mean(axis=0)
    stds = features[trainIdx].std(axis=0)
    stds[stds == 0] = 1.0
    scaledFeatures = (features - means)/stds

    torch.manual_seed(seed)
    xTrain = torch.tensor(scaledFeatures[trainIdx], dtype=torch.float32)
    yTrain = torch.tensor(labels[trainIdx], dtype=torch.float32).unsqueeze(1)
    xVal = torch.tensor(scaledFeatures[valIdx], dtype=torch.float32)
    yVal = torch.tensor(labels[valIdx], dtype=torch.float32).unsqueeze(1)

    # build the network: hidden layers with the chosen activation and a linear output layer
    layers = []
    inputSize = xTrain.shape[1]
    for size in hiddenSizes:
        layers.append(nn.Linear(inputSize, size))
        layers.append(_NN_ACTIVATIONS_TORCH[activation]())
        inputSize = size
    layers.append(nn.Linear(inputSize, 1))
    model = nn.Sequential(*layers)

    optimizer = torch.optim.Adam(model.parameters(), lr=learningRate)
    lossFunction = nn.MSELoss()

    bestValLoss = float("inf")
    bestState = copy.deepcopy(model.state_dict())
    bestEpoch = 0
    epochsSinceBest = 0
    printEvery = max(1, maxEpochs//20) # print progress roughly every 5% of maxEpochs
    lastEpoch = 0

    for epoch in range(1, maxEpochs + 1):
        lastEpoch = epoch

        # one pass over the training rows in shuffled mini-batches
        model.train()
        shuffle = torch.randperm(len(xTrain))
        for start in range(0, len(xTrain), batchSize):
            batch = shuffle[start:start+batchSize]
            optimizer.zero_grad()
            loss = lossFunction(model(xTrain[batch]), yTrain[batch])
            loss.backward()
            optimizer.step()

        model.eval()
        with torch.no_grad():
            trainLoss = lossFunction(model(xTrain), yTrain).item()
            valLoss = lossFunction(model(xVal), yVal).item()

        # keep track of the best validation epoch for early stopping
        if valLoss < bestValLoss:
            bestValLoss = valLoss
            bestState = copy.deepcopy(model.state_dict())
            bestEpoch = epoch
            epochsSinceBest = 0
        else:
            epochsSinceBest += 1

        if epoch % printEvery == 0:
            print(f"{100*epoch/maxEpochs:.0f}% (epoch {epoch}/{maxEpochs}) "
                  f"train RMSE {np.sqrt(trainLoss):.4f}, val RMSE {np.sqrt(valLoss):.4f}, "
                  f"epochs since val improved {epochsSinceBest}/{patience}")

        if epochsSinceBest >= patience:
            print(f"Early stopping at epoch {epoch}: validation loss has not improved for {patience} epochs")
            break

    # restore the weights from the epoch with the best validation loss
    model.load_state_dict(bestState)
    model.eval()
    print(f"Stopped after {lastEpoch} epochs, using weights from epoch {bestEpoch}")

    # save the weights as (inputs x outputs) arrays so the controller can do x @ W + b
    linearLayers = [layer for layer in model if isinstance(layer, nn.Linear)]
    saved = {}
    for i, layer in enumerate(linearLayers):
        saved[f"W{i}"] = layer.weight.detach().numpy().T.astype(float)
        saved[f"b{i}"] = layer.bias.detach().numpy().astype(float)
    np.savez(modelFileLoc,
             numLayers=len(linearLayers),
             means=means,
             stds=stds,
             activation=activation,
             hiddenSizes=np.array(hiddenSizes, dtype=int),
             learningRate=learningRate,
             **saved)

    # make sure the controller reloads the newly saved model on its next call
    _nnModel = None

    with torch.no_grad():
        predictions = model(torch.tensor(scaledFeatures, dtype=torch.float32)).numpy()[:,0].astype(float)
    residuals = labels - predictions
    trainRmse = np.sqrt(np.mean(residuals[trainIdx]**2))
    valRmse = np.sqrt(np.mean(residuals[valIdx]**2))
    print(f"RMSE on training rows: {trainRmse}")
    print(f"RMSE on held-out validation rows: {valRmse}")
    print(f"Model saved to {modelFileLoc}")

    # residuals (actual - predicted) against each input and against the predicted extension
    plotX = [features[:,i] for i in range(len(featureColumns))] + [predictions, data["acceleration"].to_numpy(dtype=float)]
    plotLabels = featureColumns + ["predicted extension","acceleration"]

    fig, axes = plt.subplots(2, 4, figsize=(16, 8))
    axes = axes.flatten()
    for ax, x, label in zip(axes, plotX, plotLabels):
        ax.scatter(x[trainIdx], residuals[trainIdx], s=4, alpha=0.3, label="training")
        ax.scatter(x[valIdx], residuals[valIdx], s=4, alpha=0.3, label="held-out")
        ax.axhline(0, color="red", linewidth=1)
        ax.set_xlabel(label)
        ax.set_ylabel("residual")
        ax.set_title(f"Residuals vs {label}")
    axes[-1].axis("off") # 7 plots on a 2x4 grid, so hide the unused panel
    axes[0].legend(markerscale=3)

    # title for the whole figure showing the network structure used
    fig.suptitle(f"NN residuals: layers={list(hiddenSizes)}, activation={activation}, lr={learningRate:.4g}")
    fig.tight_layout(rect=[0, 0, 1, 0.96]) # leave room at the top for the figure title
    plt.show()

