def train_linear_regression(inputFileLoc):
    """
    Loads training data, fits a linear regression for extension and prints the coefficients
    so they can be pasted into the module-level variables used by linear_regression_controller.
    Rows where undershot or overshot equal 1 are excluded from training.
    
    Args:
        inputFileLoc (string): The location of the training data csv file. Include directory and .csv in string
            Columns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate","extension","undershot","overshot"]
    
    Returns:
        None
    """
 
    data = pd.read_csv(inputFileLoc)
    totalRows = len(data)
 
    # only keep runs that neither undershot nor overshot the target apogee
    data = data[(data["undershot"] == 0) & (data["overshot"] == 0)]
    print(f"Training on {len(data)} of {totalRows} rows")
 
    featureColumns = ["altitude","velocity","acceleration","seaTemp","groundPressure","lapserate"]
    features = data[featureColumns].to_numpy(dtype=float)
    labels = data["extension"].to_numpy(dtype=float)
 
    # center and scale the features so the least squares solve is well conditioned
    # (groundPressure is ~1e5 while lapserate is ~1e-2), then convert back to raw units
    means = features.mean(axis=0)
    stds = features.std(axis=0)
    stds[stds == 0] = 1.0
    scaledFeatures = (features - means)/stds
 
    design = np.column_stack([np.ones(len(scaledFeatures)), scaledFeatures])
    solution, _, _, _ = np.linalg.lstsq(design, labels, rcond=None)
 
    coefs = solution[1:]/stds
    intercept = solution[0] - np.sum(coefs*means)
 
    predictions = features @ coefs + intercept
    rmse = np.sqrt(np.mean((predictions - labels)**2))
 
    print(f"RMSE on training data: {rmse}")
    print("Paste the following into the module-level variables:")
    print(f"lrIntercept = {float(intercept)!r}")
    print(f"lrAltCoef = {float(coefs[0])!r}")
    print(f"lrVelCoef = {float(coefs[1])!r}")
    print(f"lrAccCoef = {float(coefs[2])!r}")
    print(f"lrSeaTempCoef = {float(coefs[3])!r}")
    print(f"lrSeaPressureCoef = {float(coefs[4])!r}")
    print(f"lrLapseRateCoef = {float(coefs[5])!r}")

