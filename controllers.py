SVR_MODEL_FILE = "svr_model.npz" # where train_svr saves the model and where svr_controller loads it from

_svrModel = None # cache for the loaded model, filled on the first call of svr_controller

def svr_controller(alt,vel,acc,extension,seaTemp,seaPressure,lapseRate):
    """
    Evaluates a support vector regression model (RBF kernel) to determine the extension value.
    Loads the model saved by train_svr from SVR_MODEL_FILE on the first call and keeps it in memory.
    The output is NOT clipped to [0,1], so the raw requested extension can be inspected.
    
    Args:
        alt (float): The current altitude of the rocket in meters
        vel (float): The current vertical velocity of the rocket in m/s
        acc (float): The current acceleration of the rocket in m/s^2
        extension (float): The current extension of the Air Brakes between 0 and 1 (unused by this controller)
        seaTemp (float): The temperature at sea level in kelvin
        seaPressure (float): The pressure at sea level in pascal
        lapseRate (float): The temperature lapse rate in K/m
    
    Returns:
        targetExtension (float): The new requested target extension based on the current conditions
    """
    global _svrModel

    # load the saved model the first time the controller is called
    if _svrModel is None:
        loaded = np.load(SVR_MODEL_FILE)
        _svrModel = {key: loaded[key] for key in loaded.files}
        _svrModel["gamma"] = float(_svrModel["gamma"])
        _svrModel["intercept"] = float(_svrModel["intercept"])

    model = _svrModel

    # standardize the inputs the same way as in training (order matches the training feature columns)
    x = (np.array([alt,vel,seaTemp,seaPressure,lapseRate]) - model["means"])/model["stds"]

    # RBF kernel between the input and every support vector, then the weighted sum plus intercept
    diff = model["supportVectors"] - x
    kernel = np.exp(-model["gamma"]*np.einsum("ij,ij->i", diff, diff))

    return float(np.dot(model["dualCoef"], kernel) + model["intercept"])

