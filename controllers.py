NN_MODEL_FILE = "nn_model.npz" # where train_nn saves the model and where nn_controller loads it from

_nnModel = None # cache for the loaded model, filled on the first call of nn_controller

# activation functions supported by both the torch training code and the numpy controller
_NN_ACTIVATIONS_NUMPY = {
    "relu": lambda x: np.maximum(x, 0.0),
    "tanh": np.tanh,
    "sigmoid": lambda x: 1.0/(1.0 + np.exp(-x)),
    "silu": lambda x: x/(1.0 + np.exp(-x)),
    "leaky_relu": lambda x: np.where(x > 0, x, 0.01*x),
}
_NN_ACTIVATIONS_TORCH = {
    "relu": nn.ReLU,
    "tanh": nn.Tanh,
    "sigmoid": nn.Sigmoid,
    "silu": nn.SiLU,
    "leaky_relu": nn.LeakyReLU, # default negative slope of 0.01, matching the numpy version
}

def nn_controller(alt,vel,acc,extension,seaTemp,seaPressure,lapseRate):
    """
    Evaluates a neural network (trained by train_nn) to determine the extension value.
    Loads the model saved by train_nn from NN_MODEL_FILE on the first call and keeps it in memory.
    The forward pass is done in numpy, so torch is not needed to run the controller.
    The output is NOT clipped to [0,1], so the raw requested extension can be inspected.
    
    Args:
        alt (float): The current altitude of the rocket in meters
        vel (float): The current vertical velocity of the rocket in m/s
        acc (float): The current acceleration of the rocket in m/s^2
        extension (float): The current extension of the Air Brakes between 0 and 1 (unused by this controller)
        seaTemp (float): The temperature at sea level in kelvin
        seaPressure (float): The pressure at sea level in pascal
        lapseRate (float): The temperature lapse rate in K/m
    
    Returns:
        targetExtension (float): The new requested target extension based on the current conditions
    """
    global _nnModel

    # load the saved model the first time the controller is called
    if _nnModel is None:
        loaded = np.load(NN_MODEL_FILE)
        numLayers = int(loaded["numLayers"])
        _nnModel = {
            "weights": [loaded[f"W{i}"] for i in range(numLayers)],
            "biases": [loaded[f"b{i}"] for i in range(numLayers)],
            "means": loaded["means"],
            "stds": loaded["stds"],
            "activation": _NN_ACTIVATIONS_NUMPY[str(loaded["activation"])],
            "hiddenSizes": [int(size) for size in loaded["hiddenSizes"]],
            "activationName": str(loaded["activation"]),
            "learningRate": float(loaded["learningRate"]),
        }

    model = _nnModel
    weights = model["weights"]
    biases = model["biases"]
    activation = model["activation"]

    # standardize the inputs the same way as in training (order matches the training feature columns)
    x = (np.array([alt,vel,seaTemp,seaPressure,lapseRate]) - model["means"])/model["stds"]

    # hidden layers with the activation, then a linear output layer
    lastLayer = len(weights) - 1
    for i in range(lastLayer):
        x = activation(x @ weights[i] + biases[i])

    return float((x @ weights[lastLayer] + biases[lastLayer])[0])

